"""Generate the C and Cython declarations from Riley's extern Zig ABI types.

Run with --check to detect stale generated declarations without writing files.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/riley/zig/c-riley.zig'


def declarations():
    source = SOURCE.read_text()
    types = []
    for match in re.finditer(r'pub const (C\w+) = extern (struct|union) \{(.*?)\n?\};', source, re.S):
        fields = []
        for entry in match[3].split(','):
            entry = entry.strip()
            if not entry:
                continue
            name, field_type = entry.split(':', 1)
            fields.append((name.strip(), field_type.strip()))
        types.append((match[1], match[2], fields))
    functions = []
    for match in re.finditer(r'pub export fn (\w+)\((.*?)\) (\w+) \{', source, re.S):
        fields = []
        for entry in match[2].split(','):
            if entry.strip():
                name, field_type = entry.strip().split(':', 1)
                fields.append((name.strip(), field_type.strip()))
        functions.append((match[1], match[3], fields))
    return types, functions


def c_type(zig_type, name):
    # Dimensions may be nested; keep them in declaration order.
    dims = re.match(r'((?:\[\d+\])+)(.*)', zig_type)
    if dims:
        return c_type(dims[2], name) + dims[1]
    if zig_type.startswith('?'):
        zig_type = zig_type[1:]
    if zig_type.startswith('[*:0]const u8'):
        return 'const char* ' + name
    if zig_type.startswith('[*c]const '):
        return 'const ' + c_type(zig_type[10:], '* ' + name)
    if zig_type.startswith('[*c]'):
        return c_type(zig_type[4:], '* ' + name)
    if zig_type.startswith('*const '):
        return 'const ' + c_type(zig_type[7:], '* ' + name)
    if zig_type.startswith('*'):
        return c_type(zig_type[1:], '* ' + name)
    scalar = {'F': 'double', 'usize': 'size_t', 'u8': 'uint8_t', 'u16': 'uint16_t',
              'u32': 'uint32_t', 'c_int': 'int', 'void': 'void'}
    return scalar.get(zig_type, zig_type) + ' ' + name


def generate():
    types, functions = declarations()
    h = '/* Generated by scripts/gen_c_abi.py; edit c-riley.zig. */\n#ifndef RILEY_H\n#define RILEY_H\n#include <stddef.h>\n#include <stdint.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\n\n'
    pxd = '# Generated by scripts/gen_c_abi.py; edit c-riley.zig.\nfrom libc.stddef cimport size_t\nfrom libc.stdint cimport uint8_t, uint16_t, uint32_t\n\ncdef extern from "riley.h":\n'
    for name, kind, fields in types:
        h += f'typedef {kind} {name} {{\n'
        pxd += f'    ctypedef {kind} {name}:\n'
        for field, typ in fields:
            decl = c_type(typ, field)
            h += '    ' + decl + ';\n'
            pxd += '        ' + decl + '\n'
        h += f'}} {name};\n\n'
        pxd += '\n'
    for name, ret, fields in functions:
        args = ', '.join(c_type(typ, field) for field, typ in fields)
        h += c_type(ret, name) + '(' + (args or 'void') + ');\n'
        pxd += '    ' + c_type(ret, name) + '(' + args + ')\n'
    h += '\n#ifdef __cplusplus\n}\n#endif\n#endif\n'
    layout = '/* Generated C compiler reference for test_c_abi.zig. */\n#include "riley.h"\n\nsize_t rileyTestAbiLayout(size_t index) {\n    static const size_t layout[] = {\n'
    for name, _, fields in types:
        layout += f'        sizeof({name}), _Alignof({name}),\n'
        for field, _ in fields:
            layout += f'        offsetof({name}, {field}),\n'
    layout += '    };\n    return layout[index];\n}\n'
    return {
        ROOT / 'src/riley/cython/riley.h': h,
        ROOT / 'src/riley/cython/riley.pxd': pxd,
        ROOT / 'src/tests/c_abi_layout.c': layout,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f'Stale ABI declarations: {path}; run scripts/gen_c_abi.py')
        else:
            path.write_text(contents)


if __name__ == '__main__':
    main()
